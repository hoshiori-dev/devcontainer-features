/**
 * `ids` plus every in-repo feature they reach through dependsOn and installsAfter, transitively: what a test of
 * `ids` must be able to resolve. The CLI fetches the metadata of every installsAfter entry, so those count too.
 */
export function installClosure(model: RepoModel, ids: Iterable<string>): string[] {
    const seen = new Set<string>();
    const queue = [...ids];
    while (queue.length > 0) {
        const id = queue.shift()!;
        if (seen.has(id) || !model.features.has(id)) continue;
        seen.add(id);
        const feature = model.features.get(id)!;
        queue.push(...feature.dependsOn, ...feature.installsAfter);
    }
    return [...seen].sort();
}

/**
 * Finds one cycle through dependsOn and installsAfter, returned as the ids along it, or undefined when there is
 * none. The CLI orders both kinds of edge together, so a loop mixing them cannot be installed either.
 */
export function findInstallCycle(model: RepoModel): string[] | undefined {
    const state = new Map<string, "visiting" | "done">();
    const stack: string[] = [];
    const visit = (id: string): string[] | undefined => {
        if (state.get(id) === "done") return undefined;
        if (state.get(id) === "visiting") return [...stack.slice(stack.indexOf(id)), id];
        state.set(id, "visiting");
        stack.push(id);
        const feature = model.features.get(id);
        for (const dep of unique([...(feature?.dependsOn ?? []), ...(feature?.installsAfter ?? [])])) {
            if (!model.features.has(dep)) continue;
            const cycle = visit(dep);
            if (cycle) return cycle;
        }
        stack.pop();
        state.set(id, "done");
        return undefined;
    };
    for (const id of model.features.keys()) {
        const cycle = visit(id);
        if (cycle) return cycle;
    }
    return undefined;
}

export type PathKind =
    /** `part` is "src" for what ships in the feature's artifact, "test" for its tests. */
    | { kind: "feature"; id: string; part: "src" | "test" }
    | { kind: "global" }
    | { kind: "infra" }
    | { kind: "other" };

export function classifyPath(path: string): PathKind {
    const parts = path.split("/");
    if (parts[0] === "src" && parts.length > 2) return { kind: "feature", id: parts[1], part: "src" };
    if (parts[0] === "test" && parts.length > 2) {
        if (parts[1] === "_global") return { kind: "global" };
        if (!parts[1].startsWith("_")) return { kind: "feature", id: parts[1], part: "test" };
    }
    if (INFRA_PATHS.some((p) => (p.endsWith("/") ? path.startsWith(p) : path === p))) return { kind: "infra" };
    return { kind: "other" };
}

export interface Selection {
    /** Affected feature id → why it was selected. */
    reasons: Map<string, string>;
    runGlobal: boolean;
}

/**
 * Selects the features a set of changed paths affects. A change under src/<id> changes what users install, so it also
 * selects every feature that installs <id> through dependsOn or installsAfter — transitively, since their installed
 * result changes too — and every feature whose scenarios install one of those, without following that feature's own
 * dependents: its artifact did not change. A change under test/<id> selects only <id>. A changed id no longer in src/
 * (a deleted or renamed feature) selects nothing itself but still selects what references it. A test infrastructure
 * change adds the canaries and runs the global scenarios, so both test paths run through the changed pipeline.
 */
export function selectAffected(changed: string[], model: RepoModel): Selection {
    const reasons = new Map<string, string>();
    /** Ids whose installed result may differ: changed src/ trees and everything installing them. */
    const shipped = new Set<string>();
    let globalChanged = false;
    let infraChanged = false;
    for (const path of changed) {
        const kind = classifyPath(path);
        if (kind.kind === "feature") {
            if (model.features.has(kind.id)) reasons.set(kind.id, "changed");
            if (kind.part === "src") shipped.add(kind.id);
        } else if (kind.kind === "global") globalChanged = true;
        else if (kind.kind === "infra") infraChanged = true;
    }
    const installers = new Map<string, string[]>();
    const testers = new Map<string, string[]>();
    for (const feature of model.features.values()) {
        for (const dep of new Set([...feature.dependsOn, ...feature.installsAfter])) {
            if (dep !== feature.id) installers.set(dep, [...(installers.get(dep) ?? []), feature.id]);
        }
        for (const dep of feature.scenarioRefs) testers.set(dep, [...(testers.get(dep) ?? []), feature.id]);
    }
    const why = (id: string, verb: string) => model.features.has(id) ? `${verb} ${id}` : `references removed ${id}`;
    const queue = [...shipped];
    while (queue.length > 0) {
        const id = queue.shift()!;
        for (const dependent of installers.get(id) ?? []) {
            if (shipped.has(dependent)) continue;
            shipped.add(dependent);
            if (!reasons.has(dependent)) reasons.set(dependent, why(id, "depends on"));
            queue.push(dependent);
        }
    }
    for (const id of [...shipped].sort()) {
        for (const tester of testers.get(id) ?? []) {
            if (!reasons.has(tester)) reasons.set(tester, why(id, "tests with"));
        }
    }
    // Canaries exercise the pipeline itself; their dependents are not pulled in, keeping the set bounded.
    if (infraChanged) {
        for (const id of model.canary) if (model.features.has(id) && !reasons.has(id)) reasons.set(id, "canary");
    }
    const runGlobal = model.hasGlobal &&
        (globalChanged || infraChanged || model.globalRefs.some((id) => shipped.has(id)));
    return { reasons, runGlobal };
}

export interface TestJob {
    feature: string;
    image: string;
    arch: Arch;
    runner: string;
    remoteUser: string;
}

export interface Plan {
    tests: TestJob[];
    scenarios: { feature: string; arch: Arch; runner: string }[];
    runGlobal: boolean;
    reasons: Record<string, string>;
}

/** Expands a selection into CI matrices; throws with a fix-it message on unusable input. */
export function buildPlan(selection: Selection, model: RepoModel): Plan {
    const tests: TestJob[] = [];
    const scenarios: Plan["scenarios"] = [];
    for (const id of [...selection.reasons.keys()].sort()) {
        const feature = model.features.get(id)!;
        if (!feature.compat) {
            throw new Error(
                `test/${id}/compatibility.json is ${feature.compatError === "missing" ? "missing" : "invalid"}` +
                    (feature.compatError && feature.compatError !== "missing" ? ` (${feature.compatError})` : "") +
                    ". CI cannot know which images to test the feature on. Fix the file; see .agents/knowledge/testing.md.",
            );
        }
        for (const entry of feature.compat.images) {
            for (const arch of archesOf(entry)) {
                tests.push({
                    feature: id,
                    image: entry.image,
                    arch,
                    runner: RUNNERS[arch],
                    remoteUser: entry.remoteUser ?? "",
                });
            }
        }
        if (feature.scenarios.length > 0) {
            for (const arch of scenarioArchesOf(feature.compat)) {
                scenarios.push({ feature: id, arch, runner: RUNNERS[arch] });
            }
        }
    }
    for (const [name, count] of [["feature x image", tests.length], ["scenario", scenarios.length]] as const) {
        if (count > MATRIX_LIMIT) {
            throw new Error(
                `This change selects ${count} ${name} jobs, over GitHub's ${MATRIX_LIMIT}-job matrix limit. ` +
                    "Split the pull request so fewer features are affected at once.",
            );
        }
    }
    return { tests, scenarios, runGlobal: selection.runGlobal, reasons: Object.fromEntries(selection.reasons) };
}
