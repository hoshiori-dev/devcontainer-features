/** Every in-repo feature `feature` needs to install or test: dependsOn, installsAfter, scenarios. */
export function testEdges(feature: FeatureInfo): string[] {
    return unique([...feature.dependsOn, ...feature.installsAfter, ...feature.scenarioRefs])
        .filter((id) => id !== feature.id);
}

/** Transitive in-repo dependsOn closure of `id`, excluding `id` itself, in discovery order. */
export function dependsOnClosure(model: RepoModel, id: string): string[] {
    const seen = new Set<string>();
    const queue = [...(model.features.get(id)?.dependsOn ?? [])];
    while (queue.length > 0) {
        const next = queue.shift()!;
        if (next === id || seen.has(next)) continue;
        seen.add(next);
        queue.push(...(model.features.get(next)?.dependsOn ?? []));
    }
    return [...seen];
}

/** Finds one dependsOn cycle, returned as the ids along it, or undefined when there is none. */
export function findDependsOnCycle(model: RepoModel): string[] | undefined {
    const state = new Map<string, "visiting" | "done">();
    const stack: string[] = [];
    const visit = (id: string): string[] | undefined => {
        if (state.get(id) === "done") return undefined;
        if (state.get(id) === "visiting") return [...stack.slice(stack.indexOf(id)), id];
        state.set(id, "visiting");
        stack.push(id);
        for (const dep of model.features.get(id)?.dependsOn ?? []) {
            if (!model.features.has(dep)) continue;
            const cycle = visit(dep);
            if (cycle) return cycle;
        }
        stack.pop();
        state.set(id, "done");
        return undefined;
    };
    for (const id of model.features.keys()) {
        const cycle = visit(id);
        if (cycle) return cycle;
    }
    return undefined;
}

export type PathKind =
    | { kind: "feature"; id: string }
    | { kind: "global" }
    | { kind: "infra" }
    | { kind: "other" };

export function classifyPath(path: string): PathKind {
    const parts = path.split("/");
    if (parts[0] === "src" && parts.length > 2) return { kind: "feature", id: parts[1] };
    if (parts[0] === "test" && parts.length > 2) {
        if (parts[1] === "_global") return { kind: "global" };
        if (!parts[1].startsWith("_")) return { kind: "feature", id: parts[1] };
    }
    if (INFRA_PATHS.some((p) => (p.endsWith("/") ? path.startsWith(p) : path === p))) return { kind: "infra" };
    return { kind: "other" };
}

export interface Selection {
    /** Affected feature id → why it was selected. */
    reasons: Map<string, string>;
    runGlobal: boolean;
}

/** Selects the features a set of changed paths affects, following dependents transitively. */
export function selectAffected(changed: string[], model: RepoModel): Selection {
    const reasons = new Map<string, string>();
    let globalChanged = false;
    let infraChanged = false;
    for (const path of changed) {
        const kind = classifyPath(path);
        if (kind.kind === "feature" && model.features.has(kind.id) && !reasons.has(kind.id)) {
            reasons.set(kind.id, "changed");
        } else if (kind.kind === "global") globalChanged = true;
        else if (kind.kind === "infra") infraChanged = true;
    }
    const dependents = new Map<string, string[]>();
    for (const feature of model.features.values()) {
        for (const dep of testEdges(feature)) dependents.set(dep, [...(dependents.get(dep) ?? []), feature.id]);
    }
    const queue = [...reasons.keys()];
    while (queue.length > 0) {
        const id = queue.shift()!;
        for (const dependent of dependents.get(id) ?? []) {
            if (reasons.has(dependent)) continue;
            reasons.set(dependent, `depends on ${id}`);
            queue.push(dependent);
        }
    }
    // Canaries exercise the pipeline itself; their dependents are not pulled in, keeping the set bounded.
    if (infraChanged) {
        for (const id of model.canary) if (model.features.has(id) && !reasons.has(id)) reasons.set(id, "canary");
    }
    const runGlobal = model.hasGlobal && (globalChanged || model.globalRefs.some((id) => reasons.has(id)));
    return { reasons, runGlobal };
}

export interface TestJob {
    feature: string;
    image: string;
    arch: Arch;
    runner: string;
    remoteUser: string;
}

export interface Plan {
    tests: TestJob[];
    scenarios: { feature: string }[];
    runGlobal: boolean;
    reasons: Record<string, string>;
}

/** Expands a selection into CI matrices; throws with a fix-it message on unusable input. */
export function buildPlan(selection: Selection, model: RepoModel): Plan {
    const tests: TestJob[] = [];
    const scenarios: { feature: string }[] = [];
    for (const id of [...selection.reasons.keys()].sort()) {
        const feature = model.features.get(id)!;
        if (!feature.compat) {
            throw new Error(
                `test/${id}/compatibility.json is ${feature.compatError === "missing" ? "missing" : "invalid"}` +
                    (feature.compatError && feature.compatError !== "missing" ? ` (${feature.compatError})` : "") +
                    ". CI cannot know which images to test the feature on. Fix the file; see .agents/knowledge/testing.md.",
            );
        }
        for (const entry of feature.compat.images) {
            for (const arch of archesOf(entry)) {
                tests.push({
                    feature: id,
                    image: entry.image,
                    arch,
                    runner: RUNNERS[arch],
                    remoteUser: entry.remoteUser ?? "",
                });
            }
        }
        if (feature.scenarios.length > 0) scenarios.push({ feature: id });
    }
    for (const [name, count] of [["feature x image", tests.length], ["scenario", scenarios.length]] as const) {
        if (count > MATRIX_LIMIT) {
            throw new Error(
                `This change selects ${count} ${name} jobs, over GitHub's ${MATRIX_LIMIT}-job matrix limit. ` +
                    "Split the pull request so fewer features are affected at once.",
            );
        }
    }
    return { tests, scenarios, runGlobal: selection.runGlobal, reasons: Object.fromEntries(selection.reasons) };
}
