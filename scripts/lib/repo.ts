export function parseJsoncText(text: string): unknown {
    return parseJsonc(text);
}

/** Runs git in `cwd`; `ok` is false when it exits non-zero, and `err` carries its message. */
export async function runGit(args: string[], cwd = "."): Promise<{ ok: boolean; out: string; err: string }> {
    const output = await new Deno.Command("git", { args, cwd, stdout: "piped", stderr: "piped" }).output();
    const decode = (bytes: Uint8Array) => new TextDecoder().decode(bytes);
    return { ok: output.success, out: decode(output.stdout), err: decode(output.stderr).trim() };
}

/** Runs git and returns its output; throws with git's own message when it fails. */
export async function git(args: string[]): Promise<string> {
    const result = await runGit(args);
    if (!result.ok) throw new Error(`git ${args.join(" ")} failed: ${result.err || "no message"}`);
    return result.out;
}

export async function readJsonc(path: string): Promise<unknown> {
    return parseJsoncText(await Deno.readTextFile(path));
}

export async function exists(path: string): Promise<boolean> {
    try {
        await Deno.stat(path);
        return true;
    } catch (error) {
        if (error instanceof Deno.errors.NotFound) return false;
        throw error;
    }
}

/** Names of the directories directly under `path`, sorted; none when `path` does not exist. */
export async function listDirs(path: string): Promise<string[]> {
    if (!(await exists(path))) return [];
    const names: string[] = [];
    for await (const entry of Deno.readDir(path)) if (entry.isDirectory) names.push(entry.name);
    return names.sort();
}

/** One compiled validator per repository root, since each root has its own schema file. */
const compatValidators = new Map<string, (value: unknown) => string | undefined>();

/** Validates a parsed compatibility.json against `<root>/test/compatibility.schema.json`. */
export async function compatSchemaErrors(root: string, value: unknown): Promise<string | undefined> {
    let validator = compatValidators.get(root);
    if (!validator) {
        const schema = await readJsonc(join(root, "test", "compatibility.schema.json")) as Record<string, unknown>;
        // Loaded on first use, so scripts that never validate — tag_releases in the Release job, with its write
        // token — never evaluate the npm package or its unpinned transitive dependencies.
        const { default: Ajv } = await import("npm:ajv@8.20.0");
        // deno-lint-ignore no-explicit-any
        const ajv = new (Ajv as any)({ allErrors: true, strict: false });
        const validate = ajv.compile(schema);
        validator = (candidate) =>
            validate(candidate)
                ? undefined
                : ajv.errorsText(validate.errors, { dataVar: "compatibility.json", separator: "; " });
        compatValidators.set(root, validator);
    }
    return validator(value);
}

export async function loadFeature(root: string, id: string): Promise<FeatureInfo> {
    const info: FeatureInfo = { id, dependsOn: [], installsAfter: [], scenarioRefs: [], scenarios: [] };
    try {
        info.json = await readJsonc(join(root, "src", id, "devcontainer-feature.json")) as Record<string, unknown>;
        info.dependsOn = inRepoRefs(info.json.dependsOn);
        info.installsAfter = inRepoRefs(info.json.installsAfter);
    } catch (error) {
        info.jsonError = error instanceof Error ? error.message : String(error);
    }
    const compatPath = join(root, "test", id, "compatibility.json");
    if (!(await exists(compatPath))) {
        info.compatError = "missing";
    } else {
        try {
            const compat = await readJsonc(compatPath);
            const problem = await compatSchemaErrors(root, compat);
            if (problem) info.compatError = problem;
            else info.compat = compat as Compat;
        } catch (error) {
            info.compatError = error instanceof Error ? error.message : String(error);
        }
    }
    const scenariosPath = join(root, "test", id, "scenarios.json");
    if (await exists(scenariosPath)) {
        try {
            info.scenarios = parseScenarios(await readJsonc(scenariosPath));
        } catch (error) {
            info.scenariosError = error instanceof Error ? error.message : String(error);
        }
    }
    return info;
}

function scenarioRefs(scenarios: Scenario[]): string[] {
    return unique(
        scenarios.flatMap((s) => s.featureKeys).map(scenarioKeyId).filter((ref): ref is string => ref !== undefined),
    );
}

function errorText(error: unknown): string {
    return error instanceof Error ? error.message : String(error);
}

/**
 * Loads every feature under src/ plus the global scenarios and the canary list. Unreadable files never throw:
 * they surface as FeatureInfo errors or in `errors`, so every caller can name the file to fix.
 */
export async function loadRepo(root: string): Promise<RepoModel> {
    const features = new Map<string, FeatureInfo>();
    for (const id of await listDirs(join(root, "src"))) features.set(id, await loadFeature(root, id));
    for (const feature of features.values()) {
        feature.scenarioRefs = scenarioRefs(feature.scenarios).filter((ref) => ref !== feature.id);
    }
    const errors: Problem[] = [];
    const globalPath = join(root, "test", "_global", "scenarios.json");
    const hasGlobal = await exists(globalPath);
    let globalScenarios: Scenario[] = [];
    if (hasGlobal) {
        try {
            globalScenarios = parseScenarios(await readJsonc(globalPath));
        } catch (error) {
            errors.push({ file: "test/_global/scenarios.json", message: `unreadable: ${errorText(error)}.` });
        }
    }
    const canaryPath = join(root, "test", "canary.json");
    let canary: string[] = [];
    if (await exists(canaryPath)) {
        try {
            const value = await readJsonc(canaryPath);
            const list = value !== null && typeof value === "object" && !Array.isArray(value)
                ? (value as { features?: unknown }).features ?? []
                : undefined;
            if (!Array.isArray(list) || !list.every((id) => typeof id === "string")) {
                throw new Error('it must be {"features": ["<id>", ...]}');
            }
            canary = list;
        } catch (error) {
            errors.push({ file: "test/canary.json", message: `unreadable: ${errorText(error)}.` });
        }
    }
    return { features, globalRefs: scenarioRefs(globalScenarios), globalScenarios, hasGlobal, canary, errors };
}

/** Every test file the model could not read: scenario files, the global scenarios, the canary list. */
export function unreadableFiles(model: RepoModel): Problem[] {
    return [
        ...[...model.features.values()].flatMap((f) =>
            f.scenariosError
                ? [{ file: `test/${f.id}/scenarios.json`, message: `unreadable: ${f.scenariosError}.` }]
                : []
        ),
        ...model.errors,
    ];
}

